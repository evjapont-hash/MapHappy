// Copies the GLSL shaders out of the desktop app's C++ headers into web/js/shaders.gen.js, so the web player draws
// with exactly the same shader code. Desktop OpenGL 3.3 ("#version 330 core") becomes WebGL 2 ("#version 300 es").
//
//   node web/tools/extract-shaders.mjs           writes the file
//   node web/tools/extract-shaders.mjs --check   fails if the file is out of date (used by CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const headers = ['src/GLUtil.h', 'src/Renderer.h', 'src/PatternSource.h', 'src/GeneratorSource.h', 'src/LightingShaders.h'];
const out = join(root, 'web', 'js', 'shaders.gen.js');

const toES = src => src.replace('#version 330 core', '#version 300 es\nprecision highp float;\nprecision highp int;');

let js = '// GENERATED by web/tools/extract-shaders.mjs from the desktop app\'s C++ headers. Do not edit by hand.\n';
let count = 0;
for (const h of headers) {
  const text = readFileSync(join(root, h), 'utf8').replace(/\r\n/g, '\n');   // (Windows checkouts may have CRLF)
  const re = /inline constexpr const char\* (\w+) = R"GLSL\(([\s\S]*?)\)GLSL";/g;
  let m;
  while ((m = re.exec(text))) {
    js += `\n// from ${h}\nexport const ${m[1]} = ${JSON.stringify(toES(m[2]))};\n`;
    count++;
  }
}
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== js) { console.error('web/js/shaders.gen.js is out of date: run  node web/tools/extract-shaders.mjs'); process.exit(1); }
  console.log(`shaders.gen.js is up to date (${count} shaders)`);
} else {
  writeFileSync(out, js);
  console.log(`wrote ${out} (${count} shaders)`);
}
